#!/usr/bin/env python3
"""Build the evaluation query set.

WHAT AN EVALUATION SET IS
    A fixed list of questions, each paired with the answer we already know to
    be correct. You run the system over the list and count how often it agrees.
    The known-correct answer is called GROUND TRUTH or GOLD.

    Gold must be written down BEFORE the system runs. Otherwise you end up
    grading the system against its own output, which measures nothing.

THE DESIGN IS THE EXPERIMENT
    Queries come in TRIPLETS wherever an offence exists in both codes:

        a)  "...under Section 420 IPC?"     names the OLD code
        b)  "...under Section 318 BNS?"     names the NEW code
        c)  "My neighbour took money..."    names NEITHER

    Same offence, three phrasings. Comparing a against b shows whether the
    retriever can tell two near-identical codes apart. Comparing them against c
    shows what happens when nobody mentions a section at all -- which is how
    almost every real user asks.

FIELDS, AND WHY EACH EXISTS
    answerable_from_corpus   The index holds four Acts. A question about the
                             Limitation Act CANNOT be answered correctly, and
                             the right behaviour is refusal. Without this flag
                             those queries score as retrieval failures and
                             understate the system. With it, they measure
                             something else: does it know when it does not know?

    phrasing_register        layman or technical. Tests the hypothesis directly:
                             keyword routing works for people who cite sections
                             and fails for people who do not -- who are the
                             population this system exists to serve.

    gold_status              "verified" or "provisional". Anything depending on
                             the IPC->BNS mapping is provisional until a human
                             checks it, because that mapping was generated by
                             similarity search and is demonstrably wrong on some
                             sections (theft, robbery).

HONEST LIMIT
    This script produces the STRUCTURE and a starter set. Reaching 100+ with
    trustworthy gold requires someone who knows Indian criminal law. Gold
    annotations are a legal judgement, not a programming task.

USAGE
    python eval/build_queryset.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "eval" / "queryset.jsonl"

# --------------------------------------------------------------------------
# Paired offences. gold sections were read from the corpus text directly where
# marked verified; the rest come from the similarity mapping and need checking.
# --------------------------------------------------------------------------
PAIRS = [
    # (topic, ipc_sec, bns_sec, layman_phrasing, gold_status)
    ("murder", "302", "103",
     "My brother was killed by a neighbour during a fight. What is the punishment?", "verified"),
    ("attempt to murder", "307", "110",
     "Someone stabbed my cousin but he survived. What offence is that?", "verified"),
    ("cruelty by husband", "498A", "85",
     "My husband and his mother beat me and demand money from my parents.", "verified"),
    ("rape", "376", "64",
     "What is the punishment for rape under Indian law?", "verified"),
    ("cheating", "420", "318",
     "My neighbour took fifty thousand rupees saying he would invest it and never returned it.",
     "provisional"),
    ("theft", "379", "303",
     "Someone stole my phone from my bag in a bus.", "provisional"),
    ("robbery", "392", "309",
     "Two men snatched my chain at knifepoint on the road.", "provisional"),
    ("criminal conspiracy", "120B", "61",
     "Three people planned together to defraud my company. What offence is that?", "provisional"),
    ("dowry death", "304B", "80",
     "My sister died within two years of marriage and her in-laws had demanded a car.",
     "provisional"),
    ("criminal intimidation", "506", "351",
     "A man keeps calling me and threatening to harm my family.", "provisional"),
]

# Procedural questions. These belong to the CrPC, NOT the penal code -- the
# distinction the current Router gets wrong.
PROCEDURAL = [
    ("Police are arresting my brother without a warrant right now.",
     ["CRPC 41"], "layman"),
    ("When can a police officer arrest without a warrant under CrPC Section 41?",
     ["CRPC 41"], "technical"),
    ("The police took my father away and did not show any papers. What are his rights?",
     ["CRPC 41", "CRPC 50"], "layman"),
    ("What is anticipatory bail under Section 438 CrPC?", ["CRPC 438"], "technical"),
    ("I am afraid I will be arrested. Can I get protection before that happens?",
     ["CRPC 438"], "layman"),
    ("How long can police keep someone before producing them in court?",
     ["CRPC 57"], "layman"),
    ("What does Section 154 CrPC say about registering an FIR?", ["CRPC 154"], "technical"),
    ("The police station refused to write my complaint. What can I do?",
     ["CRPC 154", "CRPC 156"], "layman"),
    ("Powers of a Magistrate to order investigation under Section 156(3) CrPC",
     ["CRPC 156"], "technical"),
    ("Where do I file a case if the crime happened in another city?",
     ["CRPC 177", "CRPC 178"], "layman"),
]

CONSUMER = [
    ("My new refrigerator stopped working after fifteen days and the seller refuses to replace it.",
     ["CPA 2", "CPA 35"], "layman"),
    ("How do I file a complaint with the District Consumer Commission?", ["CPA 35"], "technical"),
    ("What counts as an unfair trade practice under the Consumer Protection Act 2019?",
     ["CPA 2"], "technical"),
    ("A shop sold me a fake product. Where do I complain?", ["CPA 35"], "layman"),
    ("What reliefs can a Consumer Commission grant?", ["CPA 39"], "technical"),
]

# Acts NOT in the corpus. Correct behaviour is refusal, not a confident answer.
UNANSWERABLE = [
    ("What is the punishment for a cheque bounce under Section 138 of the Negotiable Instruments Act?",
     "NI Act not indexed"),
    ("What are the grounds for divorce under the Hindu Marriage Act?", "HMA not indexed"),
    ("What is the limitation period for filing a civil suit?", "Limitation Act not indexed"),
    ("What does Article 21 of the Constitution guarantee?", "Constitution not indexed"),
    ("How is compensation calculated under the Indian Contract Act Section 73?",
     "Contract Act not indexed"),
    ("What are the penalties under the Information Technology Act for hacking?",
     "IT Act not indexed"),
    ("What is the procedure for a summary suit under Order 37 CPC?", "CPC not indexed"),
    ("What is income tax?", "not a legal-corpus question at all"),
]

MULTI_CORPUS = [
    "What is the difference between culpable homicide and murder under the IPC?",
    "Compare the punishment for cheating under the IPC and the BNS.",
    "How does the BNS differ from the IPC on offences against women?",
    "Is the arrest procedure in the CrPC different from what the BNS says about offences?",
    "A builder cheated me and also threatened me. What criminal and consumer remedies do I have?",
]


def build() -> list[dict]:
    rows: list[dict] = []
    n = 0

    def add(**kw):
        nonlocal n
        n += 1
        rows.append({"query_id": f"Q{n:03d}", **kw})

    # --- triplets -------------------------------------------------------
    for topic, ipc, bns, layman, status in PAIRS:
        pair_id = f"P_{topic.replace(' ', '_')}"
        add(pair_id=pair_id, text=f"What is the punishment for {topic} under Section {ipc} IPC?",
            category="criminal_paired", numbering_scheme="IPC",
            expected_corpus="IPC", expected_sections=[f"IPC {ipc}"],
            answerable_from_corpus=True, phrasing_register="technical",
            gold_status=status, notes=f"counterpart names BNS {bns}")
        add(pair_id=pair_id, text=f"What is the punishment for {topic} under Section {bns} BNS?",
            category="criminal_paired", numbering_scheme="BNS",
            expected_corpus="BNS", expected_sections=[f"BNS {bns}"],
            answerable_from_corpus=True, phrasing_register="technical",
            gold_status=status, notes=f"counterpart names IPC {ipc}")
        add(pair_id=pair_id, text=layman,
            category="criminal_unnumbered", numbering_scheme="none",
            expected_corpus="EITHER", expected_sections=[f"IPC {ipc}", f"BNS {bns}"],
            answerable_from_corpus=True, phrasing_register="layman",
            gold_status=status,
            notes="no section named; correct answer depends on the date of the offence")

    for text, gold, register in PROCEDURAL:
        add(pair_id=None, text=text, category="procedural", numbering_scheme="none",
            expected_corpus="CRPC", expected_sections=gold,
            answerable_from_corpus=True, phrasing_register=register,
            gold_status="verified",
            notes="PROCEDURE, not penal -- the Router currently sends these to BNS")

    for text, gold, register in CONSUMER:
        add(pair_id=None, text=text, category="consumer", numbering_scheme="none",
            expected_corpus="CPA", expected_sections=gold,
            answerable_from_corpus=True, phrasing_register=register,
            gold_status="provisional", notes="")

    for text, why in UNANSWERABLE:
        add(pair_id=None, text=text, category="unanswerable", numbering_scheme="none",
            expected_corpus=None, expected_sections=[],
            answerable_from_corpus=False, phrasing_register="mixed",
            gold_status="verified", notes=f"correct behaviour is REFUSAL -- {why}")

    for text in MULTI_CORPUS:
        add(pair_id=None, text=text, category="multi_corpus", numbering_scheme="mixed",
            expected_corpus="MULTIPLE", expected_sections=[],
            answerable_from_corpus=True, phrasing_register="mixed",
            gold_status="provisional", notes="tests the no-filter path")

    return rows


def main() -> None:
    rows = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    import collections
    cat = collections.Counter(r["category"] for r in rows)
    reg = collections.Counter(r["phrasing_register"] for r in rows)
    gold = collections.Counter(r["gold_status"] for r in rows)

    print(f"  wrote {len(rows)} queries -> {OUT.relative_to(ROOT)}\n")
    print("  BY CATEGORY")
    for k, v in cat.most_common():
        print(f"    {k:<24}{v:>4}")
    print("\n  BY PHRASING")
    for k, v in reg.most_common():
        print(f"    {k:<24}{v:>4}")
    print("\n  GOLD STATUS")
    for k, v in gold.most_common():
        print(f"    {k:<24}{v:>4}")
    print(f"\n  triplets: {len(PAIRS)} offences x 3 phrasings = {len(PAIRS)*3} queries")
    print(f"  gap to 100: {max(0, 100 - len(rows))} more needed")


if __name__ == "__main__":
    main()
